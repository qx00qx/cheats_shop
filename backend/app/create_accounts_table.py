from sqlalchemy import inspect, text

from app.database import engine


ACCOUNT_COLUMNS = {
    "categoryData": "TEXT",
    "name": "VARCHAR(255)",
    "alias": "VARCHAR(255)",
    "tabs": "TEXT",
    "prices": "TEXT",
    "text": "TEXT",
    "beforeen": "TEXT",
    "before": "TEXT",
    "entext": "TEXT",
    "video": "TEXT",
    "esp": "TEXT",
    "aimbot": "TEXT",
    "misc": "TEXT",
    "loot": "TEXT",
    "visuals": "TEXT",
    "price": "NUMERIC(12, 2)",
    "priceen": "NUMERIC(12, 2)",
    "_system_dynamic_price": "NUMERIC(12, 2) DEFAULT 0",
    "images": "TEXT",
    "fullimage": "TEXT",
    "preview": "VARCHAR(2000)",
    "vis": "INTEGER DEFAULT 1",
    "home": "INTEGER",
    "undetected": "INTEGER",
    "win10": "INTEGER",
    "win11": "INTEGER",
    "amd": "INTEGER",
    "intel": "INTEGER",
    "steam": "INTEGER",
    "mail": "INTEGER",
    "origin": "INTEGER",
    "acc": "INTEGER",
    "key": "INTEGER",
    "ubisoft": "INTEGER",
    "epic": "INTEGER",
    "other": "INTEGER",
    "all": "INTEGER",
    "posled": "INTEGER DEFAULT 999",
    "date": "TIMESTAMP",
    "meta_data": "TEXT",
    "_system": "INTEGER DEFAULT 0",
}


def main() -> None:
    with engine.begin() as conn:
        conn.execute(text(
            'CREATE TABLE IF NOT EXISTS "accounts" '
            '(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)'
        ))
        for column_name, column_type in ACCOUNT_COLUMNS.items():
            conn.execute(text(
                'ALTER TABLE "accounts" '
                f'ADD COLUMN IF NOT EXISTS "{column_name}" {column_type}'
            ))
        conn.execute(text(
            'CREATE INDEX IF NOT EXISTS ix_accounts_alias ON "accounts" (alias)'
        ))

        actual_columns = {
            column["name"]
            for column in inspect(conn).get_columns("accounts")
        }
        missing_columns = sorted(set(ACCOUNT_COLUMNS) - actual_columns)
        if missing_columns:
            raise RuntimeError(
                "Accounts schema is incomplete: " + ", ".join(missing_columns)
            )

    print("Accounts table ready; existing rows were preserved.")


if __name__ == "__main__":
    main()
