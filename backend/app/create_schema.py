def _ensure_legacy_table(
    conn: Connection,
    table_name: str,
    columns: dict[str, str],
) -> None:
    conn.execute(text(
        f'CREATE TABLE IF NOT EXISTS "{table_name}" '
        '(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)'
    ))
    for column_name, column_type in columns.items():
        conn.execute(text(
            f'ALTER TABLE "{table_name}" '
            f'ADD COLUMN IF NOT EXISTS "{column_name}" {column_type}'
        ))


def main() -> None:
    with engine.begin() as conn:
        conn.execute(text("SELECT pg_advisory_xact_lock(741205190)"))
        _ensure_legacy_table(conn, "categories", LEGACY_CATEGORY_COLUMNS)
        _ensure_legacy_table(conn, "items", LEGACY_ITEM_COLUMNS)

        conn.execute(text(
            'ALTER TABLE categories ALTER COLUMN slug DROP NOT NULL'
        ))
        conn.execute(text(
            'ALTER TABLE categories ALTER COLUMN title DROP NOT NULL'
        ))
        conn.execute(text(
            "CREATE UNIQUE INDEX IF NOT EXISTS ix_categories_slug "
            "ON categories (slug)"
        ))
        conn.execute(text(
            "CREATE INDEX IF NOT EXISTS ix_items_alias ON items (alias)"
        ))

        Base.metadata.create_all(bind=conn)

        expected_tables = set(Base.metadata.tables) | {"items"}
        existing_tables = set(inspect(conn).get_table_names())
        missing_tables = sorted(expected_tables - existing_tables)
        if missing_tables:
            raise RuntimeError(
                "Schema creation did not create all required tables: "
                + ", ".join(missing_tables)
            )

        for table_name, expected_columns in (
            ("categories", LEGACY_CATEGORY_COLUMNS),
            ("items", LEGACY_ITEM_COLUMNS),
        ):
            actual_columns = {
                column["name"]
                for column in inspect(conn).get_columns(table_name)
            }
            missing_columns = sorted(set(expected_columns) - actual_columns)
            if missing_columns:
                raise RuntimeError(
                    f"Schema creation did not add columns to {table_name}: "
                    + ", ".join(missing_columns)
                )

    print(
        f"Schema ready: {len(expected_tables)} model/legacy tables exist; "
        "legacy catalog tables are empty."
    )


if __name__ == "__main__":
    main()
